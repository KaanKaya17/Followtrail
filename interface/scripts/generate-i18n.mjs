import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(await readFile(path.join(root, 'locales/en.json'), 'utf8'));
const translations = { en: catalog };
for (const language of ['es', 'pt-BR'])
  translations[language] = JSON.parse(await readFile(path.join(root, `locales/${language}.json`), 'utf8'));
const slots = text => [...text.matchAll(/\{(\d+)\}/g)].map(m => m[1]).sort().join(',');
for (const [language, target] of Object.entries(translations)) {
  if (Object.keys(target).length !== Object.keys(catalog).length || Object.keys(target).some(key => !Object.hasOwn(catalog, key)))
    throw Error(`${language} translation coverage does not match the source catalog`);
  for (const [key, value] of Object.entries(target)) {
    const source = catalog[key];
    if (typeof source !== typeof value || !key) throw Error(`Invalid ${language} entry: ${key}`);
    const variants = typeof value === 'string' ? [value] : [value.one, value.other];
    if (typeof value === 'object' && value.count !== source.count) throw Error(`Invalid plural count: ${language}/${key}`);
    if (variants.some(text => typeof text !== 'string' || !text || slots(text) !== slots(key) || /<\/?[a-z]/i.test(text)))
      throw Error(`Invalid translation or placeholders: ${language}/${key}`);
  }
}
// Literal UI messages are checked without interpreting user content or HTML.
for (const file of ['web/archive-dashboard.js', 'web/export-browser.js', 'web/stories.js', 'web/daily-chart.js', 'web/appearance.js', 'web/desktop.js', 'web/app.js', 'web/usage-notes.js', 'web/read-health.js', 'web/request-quota.js', 'web/wayback.js', 'web/command-palette.js', 'web/operation-progress.js', 'desktop/main.cjs', 'desktop/background.cjs', 'desktop/notifications.cjs', 'desktop/read-alerts.cjs']) {
  const source = await readFile(path.join(root, file), 'utf8');
  for (const match of source.matchAll(/\bt\(("(?:[^"\\]|\\.)*")/g)) {
    const key = JSON.parse(match[1]);
    if (!Object.hasOwn(catalog, key)) throw Error(`Missing translation in ${file}: ${key}`);
  }
}
const runtime = await readFile(path.join(root, 'locales/runtime.js'), 'utf8');
if (runtime.split('/* TRANSLATIONS */ {}').length !== 2) throw Error('Translation catalog marker must occur exactly once');
const output = '// Generated by scripts/generate-i18n.mjs; edit locales/*.json and locales/runtime.js.\n' + runtime.replace('/* TRANSLATIONS */ {}', JSON.stringify(translations, null, 2));
const target = path.join(root, 'web/i18n.js');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw Error('Generated i18n.js is stale');
} else await writeFile(target, output);
console.log(`Turkish / English / Spanish / Brazilian Portuguese: ${Object.keys(catalog).length} matching messages.`);
