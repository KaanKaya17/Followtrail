import {_electron as electron} from 'playwright-core';
import {execFileSync} from 'node:child_process';
import {mkdtemp, mkdir, readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
// Sign-in-free ZIP review in the packaged EXE: partial lists, filename account,
// extra relationship lists, the relationship view on the open ZIP, comparison
// dates/renames/search/CSV, remembered results, four languages, no requests.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const python = process.env.TRACKER_BUILD_PYTHON || path.join(root, 'interface/.cache/build-venv-314/Scripts/python.exe');
const version = JSON.parse(await readFile(path.join(root, 'interface/package.json'), 'utf8')).version;
const home = await mkdtemp(path.join(os.tmpdir(), 'TrackerQA-'));
const older = path.join(home, 'instagram-qa.owner-2026-09-10-AbCdEf12.zip');
const newer = path.join(home, 'yeni-indirme.zip');
const csv = path.join(home, 'karsilastirma.csv');
execFileSync(python, ['-X', 'utf8', '-c', `
import json, sys, zipfile
P = "connections/followers_and_following/"
def fr(n, ts): return {"title":"","media_list_data":[],"string_list_data":[{"href":"https://www.instagram.com/"+n,"value":n,"timestamp":ts}]}
def fg(n, ts): return {"title":n,"string_list_data":[{"href":"https://www.instagram.com/_u/"+n,"timestamp":ts}]}
with zipfile.ZipFile(sys.argv[1], "w") as z:
    z.writestr(P+"followers_1.json", json.dumps([fr("ada",1700000000), fr("efe",1700086400), fr("mert.eski",1700172800), {"title":"","string_list_data":[]}]))
    z.writestr(P+"following.json", json.dumps({"relationships_following":[fg("ada",1690000000), fg("kitap",1690086400)]}))
    z.writestr(P+"recently_unfollowed_profiles.json", json.dumps({"relationships_unfollowed_users":[fg("eski",1699000000)]}))
    z.writestr(P+"close_friends.json", json.dumps({"relationships_close_friends":[fg("ada",1695000000), fg("kitap",1695000000)]}))
with zipfile.ZipFile(sys.argv[2], "w") as z:
    z.writestr("start_here.html", '<aside role="contentinfo">Generated by qa.owner on <time datetime="2026-10-10T12:00:00Z">x</time></aside>')
    z.writestr(P+"followers_1.json", json.dumps([fr("ada",1700000000), fr("mert.yeni",1700172800), fr("selin",1700259200)]))
    z.writestr(P+"following.json", json.dumps({"relationships_following":[fg("ada",1690000000), fg("selin",1690172800)]}))
`, older, newer]);
const output = path.join(root, `artifacts/desktop-${version}-qa/zip-archive`); await mkdir(output, {recursive: true});
const env = {...process.env}; delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({executablePath: path.join(root, `artifacts/Followtrail-Desktop-${version}/Followtrail.exe`), args: [`--tracker-test-home=${home}`], env});
const page = await app.firstWindow(); page.setDefaultTimeout(15000);
await page.setViewportSize({width: 1280, height: 900});
const errors = [], network = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
const command = (operation, args = {}) => page.evaluate(({operation, args}) => window.TrackerDesktop.command(operation, args), {operation, args});
const openDialogs = files => app.evaluate(({dialog}, files) => {
  globalThis.trackerOpenDialogs = 0;
  const original = dialog.showOpenDialog;
  dialog.showOpenDialog = () => {
    globalThis.trackerOpenDialogs++;
    const filename = files.shift();
    if (!files.length) dialog.showOpenDialog = original;
    return Promise.resolve({canceled: false, filePaths: [filename]});
  };
}, files);
const openCount = () => app.evaluate(() => globalThis.trackerOpenDialogs);
try {
  const start = page.locator('.overview-start');
  await start.getByRole('button', {name: 'Instagram ZIP’ini aç'}).waitFor();
  const before = (await command('state')).state;
  await openDialogs([older]);
  await start.getByRole('button', {name: 'Instagram ZIP’ini aç'}).click();
  const archive = page.locator('#archive-dashboard-root');
  const overview = archive.locator('.archive-dashboard-overview');
  await overview.getByRole('heading', {name: 'Arşiv kapsamı'}).waitFor();
  const coverage = await overview.innerText();
  assert.match(coverage, /@qa\.owner \(dosya adından\)/);
  assert.match(coverage, /Takipçiler\s+3\s+Kısmi · 1 satır okunamadı/);
  assert.match(coverage, /Takip ilişkileri[\s\S]*Son takipten çıktıkların\s+1[\s\S]*Yakın arkadaşlar\s+2/);
  await page.screenshot({path: path.join(output, 'overview.png')});
  checks.push('Coverage shows the filename account, a partial list with its skipped row, and extra relationship lists');

  await archive.getByRole('button', {name: 'Takip ilişkileri'}).click();
  const dialog = page.locator('#overlay-root dialog');
  await dialog.locator('#instagram-archive-filter').waitFor();
  assert.equal(await openCount(), 1);
  const options = await dialog.locator('#instagram-archive-filter option').allTextContents();
  for (const label of ['Son takipten çıktıkların · 1', 'Yakın arkadaşlar · 2', 'Seni takip etmeyen yakın arkadaşların · 1'])
    assert.ok(options.includes(label), label);
  assert.match(await dialog.locator('.notice.warning').innerText(), /Takipçiler/);
  await dialog.locator('#instagram-archive-filter').selectOption({label: 'Seni takip etmeyen yakın arkadaşların · 1'});
  assert.match(await dialog.locator('#instagram-archive-rows').innerText(), /^@kitap/);
  await page.screenshot({path: path.join(output, 'relationships.png')});
  await page.keyboard.press('Escape');
  checks.push('Takip ilişkileri reuses the open ZIP without a file dialog and lists the extra relationships');

  await openDialogs([newer]);
  await archive.getByRole('button', {name: 'İki ZIP karşılaştır'}).click();
  const body = archive.locator('.archive-dashboard-body');
  await body.getByRole('button', {name: 'İkinci ZIP’i seç'}).click();
  await body.getByRole('button', {name: 'İkinci ZIP’i değiştir'}).waitFor();
  const cards = await body.locator('.archive-dashboard-compare-sources').innerText();
  assert.match(cards, /Takipçiler\s+3 · Kısmi/);
  assert.match(cards, /yeni-indirme\.zip[\s\S]*@qa\.owner[\s\S]*Takipçiler\s+3[\s\S]*Takip edilen\s+2/);
  assert.equal(await body.getByRole('searchbox', {name: 'Sonuçlarda kullanıcı adı ara'}).isVisible(), false);
  await page.screenshot({path: path.join(output, 'sources.png')});
  checks.push('Source cards show account source and list coverage of both ZIPs before comparing');

  await body.getByRole('button', {name: 'Karşılaştırmayı başlat'}).click();
  await body.locator('.archive-dashboard-compare-count').first().waitFor();
  const results = body.locator('.archive-dashboard-rows');
  assert.match(await results.innerText(), /Listelerden biri kısmi okundu/);
  for (const summary of ['Yeni takipçiler · 1', 'Takipten çıkanlar · 1', 'Kullanıcı adını değiştirmiş olabilir · 1',
    'Takip etmeye başladıkların · 1', 'Takibi bıraktıkların · 1']) await results.getByText(summary, {exact: true}).click();
  await results.getByRole('link', {name: '@mert.yeni'}).waitFor();
  const text = await results.innerText();
  assert.match(text, /@mert\.eski → @mert\.yeni\s*Takip tarihi: /);
  assert.match(text, /@selin\s*Takip tarihi: /);
  assert.equal(await results.getByRole('button', {name: 'Daha fazla göster'}).count(), 0);
  assert.equal(await results.locator('button:visible', {hasText: 'Daha fazla göster'}).count(), 0);
  await page.screenshot({path: path.join(output, 'results.png'), fullPage: true});
  checks.push('Results use direction wording, follow dates and a probable rename; no stray "show more" button');

  await body.getByRole('searchbox', {name: 'Sonuçlarda kullanıcı adı ara'}).fill('sel');
  await page.waitForFunction(() => document.querySelectorAll('.archive-dashboard-rows a').length === 2);
  assert.match(await results.innerText(), /Aramana uyan hesap yok\./);
  await body.getByRole('searchbox', {name: 'Sonuçlarda kullanıcı adı ara'}).fill('');
  checks.push('Searching the results filters every open list on the server side');

  await app.evaluate(({dialog}, file) => { dialog.showSaveDialog = () => Promise.resolve({canceled: false, filePath: file}); }, csv);
  await body.getByRole('button', {name: 'CSV olarak kaydet'}).click();
  await body.getByText('Karşılaştırma CSV olarak kaydedildi.', {exact: true}).waitFor();
  const saved = await readFile(csv, 'utf8');
  assert.match(saved, /"followers","renamed","mert\.yeni","mert\.eski","2023-11-16"/);
  assert.match(saved, /"following","removed","kitap","","2023-07-23"/);
  checks.push('The comparison is saved as CSV with changes, previous names and UTC follow dates');

  await archive.getByRole('button', {name: 'İçerik ve etkileşim'}).click();
  await archive.getByRole('button', {name: 'İki ZIP karşılaştır'}).click();
  await body.locator('.archive-dashboard-compare-count').first().waitFor();
  assert.equal(await openCount(), 1);
  checks.push('A finished comparison is still shown after switching views, without choosing the ZIP again');
  await page.setViewportSize({width: 800, height: 900});
  await body.locator('.archive-dashboard-compare-filters').scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), false);
  await page.screenshot({path: path.join(output, 'results-narrow.png')});
  await page.setViewportSize({width: 1280, height: 900});

  // A language change rebuilds the archive view and closes the ZIP; reopen it in English.
  await command('settings', {language: 'en'});
  await page.waitForFunction(() => document.documentElement.lang === 'en');
  await openDialogs([older, newer]);
  await archive.getByRole('button', {name: 'Open Instagram ZIP'}).click();
  await archive.getByRole('heading', {name: 'Archive coverage'}).waitFor();
  await archive.getByRole('button', {name: 'Compare two ZIPs'}).click();
  await body.getByRole('button', {name: 'Choose the second ZIP'}).click();
  await body.getByRole('button', {name: 'Start comparison'}).click();
  for (const label of ['New followers · 1', 'Unfollowed you · 1', 'May have changed username · 1', 'Follow relationships'])
    await archive.getByText(label, {exact: true}).first().waitFor();
  await page.screenshot({path: path.join(output, 'results-en.png')});
  await command('settings', {language: 'tr'});
  checks.push('English coverage, comparison and rename labels are translated after reopening the ZIP');

  await page.setViewportSize({width: 800, height: 900});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), false);
  await page.screenshot({path: path.join(output, 'narrow.png')});
  const after = (await command('state')).state;
  assert.deepEqual(after.gate, before.gate);
  assert.deepEqual(errors, []); assert.deepEqual(network, []);
  checks.push('No horizontal overflow at 800 px, request gate unchanged, no network request or script error');
  await writeFile(path.join(output, 'summary.json'), JSON.stringify({checks, errors, network}, null, 2));
  console.log(`${checks.length} packaged ZIP archive checks passed.`);
} catch (error) { await page.screenshot({path: path.join(output, 'failure.png')}).catch(() => {}); throw error; }
finally { await app.close(); }
