import {waitForAccount} from './wait-for-account.mjs';
import {_electron as electron} from 'playwright-core';
import {execFileSync} from 'node:child_process';
import {mkdtemp,mkdir,readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const version=JSON.parse(await readFile(path.join(root,'interface/package.json'),'utf8')).version;
const home=await mkdtemp(path.join(os.tmpdir(),'TrackerQA-'));
const python=process.env.TRACKER_BUILD_PYTHON || path.resolve(root,'../InstagramCounter/.venv/Scripts/python.exe');
execFileSync(python,[path.join(root,'interface/desktop/backend/seed_qa.py'),'--home',home,'--accounts']);
execFileSync(python,[path.join(root,'interface/scripts/seed-daily-qa.py'),'--home',home]);
const output=path.join(root,`artifacts/desktop-${version}-qa/daily`);await mkdir(output,{recursive:true});
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE;
const app=await electron.launch({executablePath:path.join(root,`artifacts/InstagramTracker-Desktop-${version}/InstagramTracker.exe`),args:[`--tracker-test-home=${home}`],env});
const page=await app.firstWindow();page.setDefaultTimeout(15000);
const errors=[],requests=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(!/^(file:|data:)/.test(r.url()))requests.push(r.url());});
const command=(operation,args={})=>page.evaluate(({operation,args})=>window.TrackerDesktop.command(operation,args),{operation,args});
const state=async()=>(await command('state')).state;
const daily=(id='100',metric='followers',range=0,accountId='100')=>command('daily_stats',{accountId,id,metric,range});
try {
  await page.locator('.account-switcher').waitFor();
  const before=await state();assert.equal(before.history['100'].length,3);
  const all=await daily();assert.equal(all.ok,true);assert.equal(all.daily.observedDays,799);assert.ok(all.daily.points.length<=720);
  assert.equal(JSON.stringify(all).includes('session'),false);
  await page.locator('#daily-chart-root .chart-point').first().waitFor();
  assert.match(await page.locator('#daily-chart-root').innerText(),/29 gün/);
  const graphPath=await page.locator('#daily-chart-root path').getAttribute('d');assert.ok((graphPath.match(/M/g)||[]).length>1);
  checks.push('Recent history has 3 records while the real encrypted archive retains 799 observed days; missing days break the path');
  await page.locator('[data-action="daily-range"][data-value="365"]').click();
  await page.waitForFunction(()=>document.getElementById('daily-chart-root')?.textContent.includes('364 gün'));
  await page.locator('[data-action="daily-range"][data-value="0"]').click();
  await page.waitForFunction(()=>document.getElementById('daily-chart-root')?.textContent.includes('799 gün'));
  assert.ok(await page.locator('#daily-chart-root .chart-point').count()<=720);
  await page.locator('[data-action="daily-metric"][data-value="following"]').click();
  const following=await daily('100','following');assert.equal(following.daily.points.at(-1).value,399);
  await page.waitForFunction(()=>document.querySelector('#daily-chart-root .chart-summary strong')?.textContent==='399');
  checks.push('Month, year, all-history and following controls read bounded archive series without inferring missing observations');
  await page.screenshot({path:path.join(output,'daily-all.png')});
  await page.locator('[data-action="chart-source"][data-value="recent"]').click();
  assert.equal(await page.locator('.history-chart .chart-point').count(),3);
  await page.locator('[data-action="chart-source"][data-value="daily"]').click();
  await page.locator('[data-action="daily-history"]').click();
  await page.locator('#daily-dialog-chart .chart-point').first().waitFor();
  await page.getByRole('dialog').getByRole('button',{name:'Günlük geçmişi temizle',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Günlük geçmişi temizle',exact:true}).click();
  await page.getByRole('dialog').getByText('İlk başarılı kontrolün ardından günlük geçmiş burada birikir.',{exact:true}).waitFor();
  assert.equal((await daily()).daily.points.length,0);
  const after=await state();assert.deepEqual(after.history,before.history);assert.deepEqual(after.gate,before.gate);assert.deepEqual(after.lists,before.lists);
  checks.push('Explicit clearing removes daily data without reseeding retained observations or changing recent history, lists or the request gate');
  await page.keyboard.press('Escape');
  await page.locator('.sidebar a[href="#people"]').click();
  await page.locator('[data-action="person"][data-id="200"]').first().click();
  await page.getByRole('dialog').getByRole('button',{name:'Geçmiş',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Günlük geçmiş',exact:true}).click();
  await page.locator('#daily-dialog-chart .chart-point').first().waitFor();
  assert.equal((await daily('200')).daily.observedDays,799);
  checks.push('Saved profiles expose their independent long-term archive through history, even after clearing the owner archive');
  await page.keyboard.press('Escape');await page.locator('.account-switcher').click();
  await page.locator('.saved-account[data-id="400"]').click();
  await waitForAccount(page,'400');
  assert.equal((await daily()).ok,false);
  const shop=await daily('400','followers',0,'400');assert.equal(shop.ok,true);assert.ok(shop.daily.observedDays<10);
  checks.push('Switching accounts refuses stale archive queries and loads only the selected account archive');
  assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
  await writeFile(path.join(output,'checks.json'),JSON.stringify({checks,errors,externalRequests:requests,liveInstagram:false},null,2));
  console.log(`${checks.length} daily archive packaged checks passed; real DPAPI and pipe, no network.`);
} catch(error) {
  await page.screenshot({path:path.join(output,'failure.png')}).catch(()=>{});
  await writeFile(path.join(output,'failure.txt'),await page.locator('body').innerText().catch(()=>''));throw error;
} finally {await app.close();}
