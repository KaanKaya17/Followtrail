import {_electron as electron} from 'playwright-core';
import {execFileSync} from 'node:child_process';
import {mkdtemp,mkdir,readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {readHistory,waitHistory} from './read-history.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const version=JSON.parse(await readFile(path.join(root,'interface/package.json'),'utf8')).version;
const home=await mkdtemp(path.join(os.tmpdir(),'TrackerQA-'));
execFileSync(path.resolve(root,'../InstagramCounter/.venv/Scripts/python.exe'),[path.join(root,'interface/desktop/backend/seed_qa.py'),'--home',home,'--performance','--accounts']);
const output=path.join(root,`artifacts/desktop-${version}-qa/resources`);await mkdir(output,{recursive:true});
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE;
let app,page;const checks=[],errors=[],network=[];
const command=(operation,args={})=>page.evaluate(({operation,args})=>window.TrackerDesktop.command(operation,args),{operation,args});
try {
 app=await electron.launch({executablePath:path.join(root,`artifacts/Followtrail-Desktop-${version}/Followtrail.exe`),args:[`--tracker-test-home=${home}`],env});
 page=await app.firstWindow();page.setDefaultTimeout(15000);
 page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
 await page.locator('.overview-page').waitFor();const state=(await command('state')).state;
 assert.equal(state.events.length,5);assert.equal(state.notificationLog.length,0);
 assert.equal(state.historyMeta.events,2000);assert.equal(state.historyMeta.notificationCounts.all.all,500);
 const events=await readHistory(page,'events',state),logs=await readHistory(page,'notifications',state);
 assert.equal(events.length,2000);assert.equal(logs.length,500);
 const foreign=await command('history_page',{accountId:'400',revision:state.historyMeta.revision,kind:'events',type:'all',personId:'',section:'all',read:'all',offset:0});
 assert.equal(foreign.ok,false);assert.equal(foreign.page,undefined);
 checks.push('Regular IPC carries five recent events and counts, while explicit local paging retrieves all 2000 retained events and 500 notification groups; foreign accounts fail closed');
 await page.evaluate(()=>window.qaNodes={stat:document.querySelector('.stat-value'),nav:document.querySelector('.sidebar nav'),chart:document.getElementById('daily-chart-root')});
 await app.evaluate(({BrowserWindow},state)=>BrowserWindow.getAllWindows()[0].webContents.send('tracker:event',{type:'result',state:{...state,account:{...state.account,followers:state.account.followers+1}}}),state);
 await page.waitForFunction(value=>document.querySelector('.stat-value').textContent===String(value),state.account.followers+1);
 assert.equal(await page.evaluate(()=>qaNodes.stat===document.querySelector('.stat-value') && qaNodes.nav===document.querySelector('.sidebar nav') && qaNodes.chart===document.getElementById('daily-chart-root')),true);
 await page.locator('.sidebar nav a[href="#people"]').click();await page.locator('#people-search').fill('qa');
 await page.locator('#people-search').evaluate(node=>{node.focus();node.setSelectionRange(0,2);window.qaInput=node;});
 await command('settings',{compact:true});await page.waitForFunction(()=>document.body.dataset.density==='compact');
 assert.deepEqual(await page.locator('#people-search').evaluate(node=>({same:node===qaInput,focus:node===document.activeElement,value:node.value,start:node.selectionStart,end:node.selectionEnd})),{same:true,focus:true,value:'qa',start:0,end:2});
 checks.push('A visible counter change patches the same counter/nav/chart nodes; real settings updates preserve the same focused search field and selection');
 await page.locator('.sidebar nav a[href="#timeline"]').click();await waitHistory(page);
 assert.equal(await page.locator('.timeline-event').count(),100);
 const first=await page.locator('.timeline-event').first().getAttribute('data-id');
 await page.locator('.timeline-event').first().evaluate(node=>window.qaFirstEvent=node);
 await page.locator('[data-action="more-events"]').click();await waitHistory(page);
 assert.equal(await page.locator('.timeline-event').count(),200);
 assert.equal(await page.locator(`.timeline-event[data-id="${first}"]`).evaluate(node=>node===qaFirstEvent),true);
 await command('read_notification',{id:logs[0].id});await waitHistory(page);
 assert.equal(await page.locator('.timeline-event').count(),200);
 assert.equal(await page.locator(`.timeline-event[data-id="${first}"]`).evaluate(node=>node===qaFirstEvent),true);
 await page.locator('.sidebar nav a[href="#notifications"]').click();await waitHistory(page);
 assert.equal(await page.locator('.notification-card').count(),100);
 await page.locator('[data-action="more-notifications"]').click();await waitHistory(page);assert.equal(await page.locator('.notification-card').count(),200);
 await page.locator('.notification-card').last().click();await page.locator('.change-log-details').waitFor();await page.keyboard.press('Escape');
 checks.push('Timeline and notifications fetch 100 records per page, preserve existing row nodes on append and open full retained details on demand');
 const before=(await command('state')).state;
 await command('switch_account',{id:'400'});await page.waitForFunction(()=>location.hash==='#overview');
 const old=await command('history_detail',{accountId:'100',revision:before.historyMeta.revision,kind:'notification',id:logs[0].id});assert.equal(old.ok,false);
 assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
 await writeFile(path.join(output,'summary.json'),JSON.stringify({checks,errors,network},null,2));
 console.log(JSON.stringify({checks:checks.length,errors,network,output}));
}catch(error){console.error(JSON.stringify({errors,network}));await page?.screenshot({path:path.join(output,'failure.png')}).catch(()=>{});throw error;}
finally{await app?.close();}
