import { _electron as electron } from 'playwright-core';
import {execFileSync} from 'node:child_process';
import {mkdtemp,mkdir,readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const python=process.env.TRACKER_BUILD_PYTHON || path.resolve(root,'../InstagramCounter/.venv/Scripts/python.exe');
const version=JSON.parse(await readFile(path.join(root,'interface/package.json'),'utf8')).version;
const home=await mkdtemp(path.join(os.tmpdir(),'TrackerQA-'));
for(const script of ['interface/desktop/backend/seed_qa.py','interface/scripts/seed-story-qa.py'])
 execFileSync(python,[path.join(root,script),'--home',home,...(script.includes('seed_qa.py')?['--accounts']:[])],{stdio:'pipe'});
const output=path.join(root,`artifacts/desktop-${version}-qa/stories`);await mkdir(output,{recursive:true});
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE;
const app=await electron.launch({executablePath:path.join(root,`artifacts/InstagramTracker-Desktop-${version}/InstagramTracker.exe`),args:[`--tracker-test-home=${home}`],env});
const page=await app.firstWindow();page.setDefaultTimeout(15000);
const errors=[],network=[],checks=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('request',request=>{if(/^https?:/.test(request.url()))network.push(request.url());});
const command=(operation,args={})=>page.evaluate(({operation,args})=>window.TrackerDesktop.command(operation,args),{operation,args});
try {
 await page.locator('.account-switcher').waitFor();
 const before=(await command('state')).state;
 await page.locator('.sidebar a[href="#people"]').click();
 await page.locator('[data-action="person"][data-id="200"]').first().click();
 await page.locator('[data-action="story-archive"]').click();
 await page.locator('.story-card').first().waitFor();
 assert.equal(await page.locator('.story-card').count(),2);
 assert.match(await page.locator('#story-archive-root').innerText(),/qa.tagged/);
 assert.match(await page.locator('#story-archive-root').innerText(),/Hikâyede paylaşılan gönderi/);
 checks.push('Profile opens two local dated records with mentions, links and source-post reference');
 await page.locator('[data-action="story-play"]:not([disabled])').click();
 await page.waitForFunction(()=>document.querySelector('#story-player img')?.naturalWidth===360);
 const blob=await page.locator('#story-player img').getAttribute('src');assert.match(blob,/^blob:/);
 const state=(await command('state')).state;assert.equal(JSON.stringify(state.storyDetail).includes('base64'),false);assert.equal(state.storyMedia,undefined);
 assert.deepEqual(state.gate,before.gate);
 checks.push('Actual encrypted JPEG decrypts and displays on demand, outside snapshots and without gate changes');
 await page.screenshot({path:path.join(output,'story-archive.png')});
 await page.locator('#story-date').fill('2027-01-01');
 assert.equal(await page.locator('.story-card').count(),0);
 await page.locator('#story-date').fill('');assert.equal(await page.locator('.story-card').count(),2);
 await page.keyboard.press('Escape');assert.equal(await page.locator('#overlay-root dialog[open]').count(),0);
 const revocation=await page.evaluate(async url=>{try{await fetch(url);return false;}catch{return true;}},blob);
 assert.equal(revocation,true);
 checks.push('Date filter has an explanatory empty state; closing revokes playback resources');
 for(const [language,title] of [['en','Story archive · Experimental'],['es','Archivo de historias · Experimental'],['pt-BR','Arquivo de stories · Experimental'],['tr','Hikâye arşivi · Deneysel']]) {
  await command('settings',{language});
  await page.waitForFunction(language=>document.documentElement.lang===language,language);
  await page.locator('[data-action="person"][data-id="200"]').first().click();
  await page.locator('[data-action="story-archive"]').click();
  await page.locator('.story-card').first().waitFor();
  assert.equal(await page.locator('#dialog-title').innerText(),title);
  await page.keyboard.press('Escape');
 }
 await command('settings',{theme:'dark'});
 await page.locator('[data-action="person"][data-id="200"]').first().click();
 await page.locator('[data-action="story-archive"]').click();
 await page.locator('.story-card').first().waitFor();
 await page.screenshot({path:path.join(output,'story-archive-dark.png')});
 await page.keyboard.press('Escape');
 checks.push('The archive opens in all four app languages and uses the shared dark theme');
 const foreign=await command('story_media',{accountId:'101',id:'200',storyId:'300'});assert.equal(foreign.ok,false);
 const offline=await command('story_fetch',{accountId:'100',id:'200'});assert.equal(offline.ok,false);assert.equal(offline.error.code,'offline');
 checks.push('Cross-account media is rejected and isolated test mode refuses live fetches');
 const view=await command('story_view',{accountId:'100',id:'200'});assert.equal(view.state.storyDetail.items.length,2);
 await command('story_clear',{accountId:'100',id:'200'});
 assert.equal((await command('story_view',{accountId:'100',id:'200'})).state.storyDetail.items.length,0);
 assert.deepEqual((await command('state')).state.gate,before.gate);
 checks.push('Clearing deletes only the selected profile story archive without touching the request gate');
 assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
 await writeFile(path.join(output,'summary.json'),JSON.stringify({checks,errors,network,home},null,2));
 console.log(JSON.stringify({checks:checks.length,errors,network,output}));
} finally {await app.close();}
