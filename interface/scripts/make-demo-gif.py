"""Helpers for scripts/capture-readme-demo.mjs.

  make-demo-gif.py exports <older.zip> <newer.zip>   write two synthetic Instagram exports
  make-demo-gif.py gif <frames dir> <out.gif> <ms,ms,...>   join PNG frames into a GIF

All accounts are invented (demo.*); nothing comes from a real export.
"""
import json
import random
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path

FOLDER = 'connections/followers_and_following/'
DAY = 86400
WIDTH = 960


def names(count, start=0):
    first = ['deniz', 'ada', 'efe', 'ela', 'mert', 'zeynep', 'can', 'irem', 'arda', 'selin', 'kaan', 'derin']
    return [f'demo.{first[i % len(first)]}{i:02d}' for i in range(start, start + count)]


def export(path, now, followers, following, rng, activity, dates):
    # A follow date belongs to the relationship, so it is the same in every export.
    def fr(name):
        return {'title': '', 'string_list_data': [{'href': 'https://www.instagram.com/' + name, 'value': name,
                                                     'timestamp': dates[name]}]}

    def fg(name):
        return {'title': name, 'string_list_data': [{'href': 'https://www.instagram.com/_u/' + name,
                                                     'timestamp': dates['following:' + name]}]}

    def moment():
        hour = rng.choice([8, 12, 13, 18, 20, 21, 21, 22, 22, 23])
        return now - rng.randint(1, 600) * DAY - now % DAY + hour * 3600 + rng.randint(0, 3599)

    targets = following[len(following) // 3:]
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as archive:
        stamp = datetime.fromtimestamp(now, timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
        archive.writestr('start_here.html', '<aside role="contentinfo">Generated by demo.account on '
                         f'<time datetime="{stamp}">x</time></aside>')
        archive.writestr(FOLDER + 'followers_1.json', json.dumps([fr(name) for name in followers]))
        archive.writestr(FOLDER + 'following.json', json.dumps({'relationships_following': [fg(name) for name in following]}))
        archive.writestr(FOLDER + 'close_friends.json', json.dumps({'relationships_close_friends': [fg(n) for n in following[:6]]}))
        if not activity:
            return
        archive.writestr('your_instagram_activity/likes/liked_posts.json', json.dumps({'likes_media_likes': [
            {'title': rng.choice(targets), 'string_list_data': [{'timestamp': moment()}]} for _ in range(700)]}))
        archive.writestr('your_instagram_activity/comments/post_comments_1.json', json.dumps([
            {'string_map_data': {'Comment': {'value': '✨'}, 'Media Owner': {'value': rng.choice(targets)},
                                 'Time': {'timestamp': moment()}}} for _ in range(90)]))
        archive.writestr('your_instagram_activity/story_interactions/story_likes.json', json.dumps({
            'story_activities_story_likes': [{'title': rng.choice(targets), 'string_list_data': [{'timestamp': moment()}]}
                                             for _ in range(160)]}))
        archive.writestr('your_instagram_activity/media/posts_1.json', json.dumps([
            {'media': [{'uri': f'media/posts/{i}.jpg', 'creation_timestamp': moment()}]} for i in range(18)]))


def exports(older, newer):
    rng = random.Random(20261101)
    first = int(datetime(2026, 8, 1, 12, tzinfo=timezone.utc).timestamp())
    second = int(datetime(2026, 11, 1, 12, tzinfo=timezone.utc).timestamp())
    base = names(64)
    old_followers, old_following = base[:52], base[8:]
    dates = {name: first - rng.randint(30, 1500) * DAY for name in base}
    dates.update({'following:' + name: first - rng.randint(30, 1800) * DAY for name in base})
    # Three months later: four new followers, three left, one renamed, two follows dropped.
    arrivals = names(4, 70)
    dates.update({name: first + rng.randint(5, 85) * DAY for name in arrivals})
    dates['demo.yeni.ad'] = dates[base[20]]
    new_followers = [n for n in old_followers if n not in base[10:13]] + arrivals
    new_followers = [('demo.yeni.ad' if n == base[20] else n) for n in new_followers]
    new_following = [n for n in old_following if n not in base[60:62]]
    export(Path(older), first, old_followers, old_following, random.Random(1), False, dates)
    export(Path(newer), second, new_followers, new_following, rng, True, dates)


def gif(frames_dir, output, durations):
    from PIL import Image
    paths = sorted(Path(frames_dir).glob('*.png'))
    delays = [int(value) for value in durations.split(',')]
    if not paths or len(paths) != len(delays):
        raise SystemExit(f'{len(paths)} frames for {len(delays)} durations')
    images = []
    for path in paths:
        with Image.open(path) as image:
            image = image.convert('RGB')
            image = image.resize((WIDTH, round(image.height * WIDTH / image.width)), Image.Resampling.LANCZOS)
            images.append(image.quantize(colors=128, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE))
    images[0].save(output, save_all=True, append_images=images[1:], duration=delays, loop=0, optimize=True)
    print(f'{output}: {len(images)} frames, {Path(output).stat().st_size // 1024} KiB')


if __name__ == '__main__':
    command = sys.argv[1] if len(sys.argv) > 1 else ''
    if command == 'exports' and len(sys.argv) == 4:
        exports(*sys.argv[2:])
    elif command == 'gif' and len(sys.argv) == 5:
        gif(*sys.argv[2:])
    else:
        raise SystemExit(__doc__)
