import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdir, mkdtemp, readFile, rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { _electron as electron } from 'playwright-core';

const [exe, folder, language = 'tr'] = process.argv.slice(2);
if (!exe || !folder || !['tr','en','es','pt-BR'].includes(language)) {
    throw new Error('Usage: node capture-archive-docs.mjs <InstagramTracker.exe> <output-directory> [tr|en|es|pt-BR]');
}
const executablePath = path.resolve(exe);
const output = path.resolve(folder);
const messages = language === 'tr' ? {} :
    JSON.parse(await readFile(new URL(`../locales/${language}.json`, import.meta.url), 'utf8'));
const t = key => {
    if (language === 'tr') return key;
    assert.ok(messages[key], key);
    return messages[key];
};

const home = await mkdtemp(path.join(os.tmpdir(), 'TrackerQA-'));
let desktop;
try {
    const older = path.join(home, 'ornek-eski.zip');
    const newer = path.join(home, 'ornek-yeni.zip');
    execFileSync(process.env.TRACKER_BUILD_PYTHON || 'python', ['-X', 'utf8', '-c', [
        'import json, sys, zipfile',
        'def rows(names):',
        '    return [{"string_list_data":[{"value":name,"timestamp":1788343200}]} for name in names]',
        'for filename, date, followers, following in [',
        '    (sys.argv[1], "2026-09-10", ["ornek.deniz","ornek.efe","ornek.selin"], ["ornek.deniz","ornek.kitaplik"]),',
        '    (sys.argv[2], "2026-10-10", ["ornek.deniz","ornek.selin","ornek.ada","ornek.mert"], ["ornek.deniz","ornek.ada","ornek.kitaplik"])]:',
        '    with zipfile.ZipFile(filename,"w") as archive:',
        '        archive.writestr("start_here.html", f\'<aside role="contentinfo">Generated by ornek.hesap on <time datetime="{date}T12:00:00Z">{date}</time></aside>\')',
        '        prefix = "connections/followers_and_following/"',
        '        archive.writestr(prefix+"followers_1.json", json.dumps(rows(followers)))',
        '        archive.writestr(prefix+"following.json", json.dumps({"relationships_following":rows(following)}))',
        '        archive.writestr("your_instagram_activity/messages/inbox/ornek/message_1.json", json.dumps({"title":"Gezi planı","messages":[{"sender_name":"Deniz Örnek","timestamp_ms":1788343200000,"content":"Hafta sonu sahilde buluşalım."}]}))',
        '        archive.writestr("your_instagram_activity/likes/liked_posts.json", json.dumps([{"title":"Örnek gönderi","timestamp":1788343200}]))',
        '        archive.writestr("your_instagram_activity/media/posts_1.json", json.dumps([{"media":[{"title":"Sahilde bir pazar","creation_timestamp":1788343200}]}]))',
    ].join('\n'), older, newer]);

    const env = {...process.env};
    delete env.ELECTRON_RUN_AS_NODE;
    desktop = await electron.launch({executablePath, args:['--tracker-test-home='+home], env});
    const page = await desktop.firstWindow();
    await page.setViewportSize({width:1440, height:1000});
    const errors = [];
    const external = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route(/^https?:/, async route => {
        external.push(route.request().url());
        await route.abort();
    });
    await mkdir(output, {recursive:true});
    const capture = (name, target = page) => target.screenshot({path:path.join(output,name+'.png'), animations:'disabled'});
    if (language !== 'tr') {
        await page.locator('.sidebar nav a[href="#settings"]').click();
        await page.locator('#app-language').selectOption(language);
        await page.waitForFunction(value => document.documentElement.lang === value, language);
        await page.locator('#toast.visible').waitFor({state:'hidden'});
        await page.locator('.sidebar nav a[href="#overview"]').click();
    }
    await page.mouse.move(0,0);

    const start = page.locator('.overview-start');
    const open = start.getByRole('button',{name:t('Instagram ZIP’ini aç')});
    await open.waitFor();
    const before = (await page.evaluate(() => window.TrackerDesktop.command('state'))).state;
    assert.equal(before.connected,false);
    await capture('ilk-acilis', start);
    await desktop.evaluate(({dialog}, files) => {
        const original = dialog.showOpenDialog;
        dialog.showOpenDialog = () => {
            const filename = files.shift();
            if (!files.length) dialog.showOpenDialog = original;
            return Promise.resolve({canceled:false,filePaths:[filename]});
        };
    }, [older,newer]);
    await open.click();
    const archive = page.locator('#archive-dashboard-root');
    await archive.getByRole('heading',{name:t('Arşiv kapsamı')}).waitFor();
    const coverage = archive.locator('.archive-dashboard-coverage');
    assert.deepEqual((await coverage.locator('li').allTextContents()).slice(0,2),
        [t('Takipçiler')+'3',t('Takip edilen')+'2']);
    await capture('zip-arsiv');

    await archive.getByRole('button',{name:t('İçerik ve etkileşim'),exact:true}).click();
    await archive.getByText('Sahilde bir pazar',{exact:true}).waitFor();
    await capture('zip-icerik-takvimi',archive.locator('.archive-dashboard-body'));

    await archive.getByRole('button',{name:t('İki ZIP karşılaştır')}).click();
    await archive.getByRole('button',{name:t('İkinci ZIP’i seç')}).click();
    const run = archive.getByRole('button',{name:t('Karşılaştırmayı başlat')});
    await run.waitFor();
    const accounts = archive.locator('.archive-dashboard-compare-sources').getByText('@ornek.hesap',{exact:true});
    await accounts.nth(1).waitFor();
    assert.equal(await accounts.count(),2);
    const comparison = archive.locator('.archive-dashboard-body');
    await capture('zip-karsilastirma-kaynaklar', comparison);
    await run.click();
    const summary = archive.locator('.archive-dashboard-compare-count').first();
    await summary.waitFor();
    assert.equal(await summary.innerText(),'3 → 4');
    await archive.getByText(t('Yalnız ilk ZIP’te')+' · 1',{exact:true}).click();
    await archive.getByText(t('Yalnız ikinci ZIP’te')+' · 2',{exact:true}).click();
    for (const username of ['@ornek.efe','@ornek.ada','@ornek.mert']) {
        await archive.getByRole('link',{name:username,exact:true}).first().waitFor();
    }
    await capture('zip-karsilastirma-sonuc', comparison.locator(':scope > .archive-dashboard-rows'));
    const after = (await page.evaluate(() => window.TrackerDesktop.command('state'))).state;
    assert.equal(after.connected,false);
    assert.deepEqual(after.gate,before.gate);
    assert.deepEqual(errors,[]);
    assert.deepEqual(external,[]);
    console.log('Five documentation screenshots captured with two synthetic ZIPs and no external requests.');
} finally {
    if (desktop) await desktop.close();
    await rm(home,{recursive:true,force:true,maxRetries:3,retryDelay:200});
}
