package dev.kaankaya.instagramtracker

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertThrows
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

class InstagramArchiveTest {
    @get:Rule val folder = TemporaryFolder()
    private val prefix = "connections/followers_and_following/"

    private fun read(vararg entries: Pair<String, String>): InstagramArchive {
        return zip(*entries).inputStream().use { InstagramArchive.read(it, folder.root) }
    }

    private fun zip(vararg entries: Pair<String, String>): java.io.File {
        val file = folder.newFile()
        ZipOutputStream(file.outputStream()).use { zip ->
            for ((name, value) in entries) {
                zip.putNextEntry(ZipEntry(name))
                zip.write(value.toByteArray(Charsets.UTF_8))
                zip.closeEntry()
            }
        }
        return file
    }

    @Test fun exportBrowserPreservesCoverageRangeLongSearchAndCalendarMetrics() {
        val file = zip(
            "start_here.html" to """<aside role="contentinfo">Generated by sample on <time datetime="2024-03-02T00:00Z">Export</time><div>Contains data you requested from <time datetime="2024-01-01T00:00Z">Start</time> to <time datetime="2024-03-01T00:00Z">End</time></div></aside>""",
            prefix + "followers_1.json" to "[]",
            "your_instagram_activity/messages/inbox/example/message_1.json" to """{"messages":[{"content":"${"a".repeat(8200)} unique_end"}]}""",
            "your_instagram_activity/likes/liked_posts.json" to """[{"timestamp":1704103200},{"timestamp":1709287200}]""",
            "your_instagram_activity/media/reels.json" to """{"ig_reels_media":[{"media":[{"uri":"media/reel.mp4","title":"Original","creation_timestamp":1709287200}]}]}""",
            "logged_information/past_instagram_insights/reels.json" to """{"organic_insights_reels":[{"media_map_data":{"Media Thumbnail":{"uri":"media/reel.mp4"}},"string_map_data":{"Upload Timestamp":{"timestamp":1709287200},"Instagram Likes":{"value":"0"},"Instagram Plays":{"value":"100"}}}]}""",
        )
        ExportBrowser.open(file).use { browser ->
            val scope = browser.coverage("example.zip")
            assertEquals("sample", scope.username)
            assertEquals("2024-03-02T00:00:00Z", scope.exportedAt)
            assertEquals("2024-01-01" to "2024-03-01", scope.dateRange)
            assertEquals(true, scope.hasFollowers)
            assertEquals(false, scope.hasFollowing)
            assertEquals(true, scope.hasMessages)
            assertEquals(emptyList<InstagramArchiveRow>(), browser.relationships().followers)
            val hit = browser.search("unique_end", 0, -1).hits.single()
            assertEquals(0, hit.record)
            assertEquals(true, hit.excerpt.endsWith("unique_end"))
            assertEquals(listOf("2024-01" to 1, "2024-02" to null, "2024-03" to 1), browser.likedMonths())
            val reel = browser.contentHistory().items.single()
            assertEquals("Original", reel.caption)
            assertEquals(mapOf("likes" to 0L, "plays" to 100L), reel.metrics)
        }
    }

    @Test fun readsSplitRelationshipFilesAndIgnoresOtherCategories() {
        val lists = read(
            prefix + "followers_1.json" to """[{"string_list_data":[{"value":"Alice","timestamp":1700000000}]}]""",
            prefix + "followers_2.json" to """[{"string_list_data":[{"value":"alice","timestamp":1710000000}]},{"string_list_data":[{"value":"carol","timestamp":1700000001}]}]""",
            prefix + "following.json" to """{"relationships_following":[{"title":"alice","string_list_data":[{"href":"https://www.instagram.com/_u/alice","timestamp":1720000000}]},{"string_list_data":[{"href":"https://www.instagram.com/_u/bob","timestamp":true}]}]}""",
            "messages/inbox/ignored.json" to "invalid JSON",
        )
        assertEquals(listOf(InstagramArchiveRow("alice"), InstagramArchiveRow("carol", 1700000001)), lists.followers)
        assertEquals(listOf(InstagramArchiveRow("alice", 1720000000), InstagramArchiveRow("bob")), lists.following)
        assertEquals(1, folder.root.listFiles()?.size)
    }

    @Test fun readsHtmlLinksOnlyInsideTheMainList() {
        val lists = read(prefix + "following.html" to """
            <html><body><header><a href="https://www.instagram.com/ignored/">Navigation</a></header>
            <main><div><h2>Alice</h2><a href="https://www.instagram.com/_u/Alice">Link</a></div>
            <div><a href="https://www.instagram.com/bob/">Link</a></div></main></body></html>
        """.trimIndent())
        assertNull(lists.followers)
        assertEquals(listOf(InstagramArchiveRow("alice"), InstagramArchiveRow("bob")), lists.following)
    }

    @Test fun distinguishesEmptyAndMissingAndRejectsMissingParts() {
        val lists = read(prefix + "followers_1.json" to "[]")
        assertEquals(emptyList<InstagramArchiveRow>(), lists.followers)
        assertNull(lists.following)
        assertThrows(IllegalArgumentException::class.java) { read(prefix + "followers_2.json" to "[]") }
        assertThrows(IllegalArgumentException::class.java) {
            read(prefix + "followers_1.json" to "[]", "other/" + prefix + "following.json" to "[]")
        }
        assertThrows(IllegalArgumentException::class.java) {
            read(prefix + "followers_1.json" to """[{"title":"alice","string_list_data":[{"value":"bob"}]}]""")
        }
    }

    @Test fun comparesEqualTotalsByUsernameAndPreservesMissingDirection() {
        fun rows(vararg names: String) = names.map { InstagramArchiveRow(it) }
        val before = InstagramArchive(rows("alice", "bob"), rows("alice"))
        val after = InstagramArchive(rows("alice", "carol"), null)
        val (followers, following) = before.compare(after)
        assertEquals(InstagramArchive.Difference(2, 2, listOf("carol"), listOf("bob")), followers)
        assertNull(following)
    }
}
